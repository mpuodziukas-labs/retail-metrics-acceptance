"""Pure renderers: metrics dict in, text out. No numbers are typed by hand."""
from html import escape

FMT = {"money": lambda v: f"{v:,.2f}", "money0": lambda v: f"{v:,.0f}",
       "int": lambda v: f"{int(v):,}", "pct": lambda v: f"{v:.2f}%", "str": str}


def f(kind, v):
    return FMT[kind](v)


def _peak(m):
    return max(m["monthly"], key=lambda r: r["revenue"])


def results_block(m):
    h = m["headline"]
    ok = sum(1 for c in m["quality"] if c["ok"])
    peak = _peak(m)
    rows = [
        ("Rows loaded", f("int", h["rows_loaded"])),
        ("Revenue, clean order lines", f("money", h["revenue_total"])),
        ("Orders", f("int", h["orders"])),
        ("Average order value", f("money", h["aov"])),
        ("Customers with an ID", f("int", h["customers"])),
        ("Repeat-purchase rate", f("pct", h["repeat_purchase_rate_pct"])),
        ("Revenue share from repeat customers (identified customers)",
         f("pct", h["repeat_revenue_share_pct"])),
        ("Revenue with no customer ID", f("pct", h["guest_revenue_share_pct"])),
        ("Cancellation rate (invoices)", f("pct", h["cancellation_rate_pct"])),
        ("Month-1 cohort retention", f("pct", h["month1_retention_pct"])),
        ("Peak revenue month", f"{peak['month']} ({f('money', peak['revenue'])})"),
        ("Quality checks passing", f"{ok}/{len(m['quality'])}"),
    ]
    lines = ["Generated by `make regen` from `out/metrics.json`. Do not edit by hand.", "",
             "| Metric | Value |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in rows]
    return "\n".join(lines)


def recommendation(m):
    h, peak = m["headline"], _peak(m)
    total = h["revenue_total"]
    return f"""# Recommendations

Generated by `make regen` from `out/metrics.json`. Every number below is read from that file; none is typed by hand.

## 1. Move first-time buyers to a second order

What the data shows: {f('int', h['repeat_customers'])} of {f('int', h['customers'])} identified customers ({f('pct', h['repeat_purchase_rate_pct'])}) ordered more than once. Those repeat customers account for {f('pct', h['repeat_revenue_share_pct'])} of identified-customer revenue. Only {f('pct', h['month1_retention_pct'])} of a cohort orders again in the month after its first order.

Recommendation: target the first-month window with a second-order offer or reminder, and track month-1 retention as the success measure.

## 2. Capture a customer ID at checkout

What the data shows: {f('pct', h['guest_revenue_share_pct'])} of revenue comes from lines with no customer ID, so none of the repeat or cohort metrics above can see it.

Recommendation: ask for an identifier at checkout so the unattributed share shrinks, then re-run this pipeline and compare the share.

## 3. Plan for the peak month and its cancellations

What the data shows: {peak['month']} is the highest revenue month at {f('money', peak['revenue'])}, which is {f('pct', 100 * peak['revenue'] / total)} of the period total. Its invoice cancellation rate is {f('pct', peak['cancellation_rate_pct'])}, against {f('pct', h['cancellation_rate_pct'])} over the whole period.

Recommendation: plan stock and support capacity ahead of {peak['month']}, and review cancellations in that month first.
"""


def _t(tag, k, kind, v, attrs=""):
    return f'<{tag} data-k="{k}" data-f="{kind}"{attrs}>{escape(f(kind, v))}</{tag}>'


def _bars(m):
    mm = m["monthly"]
    top = max(r["revenue"] for r in mm)
    w, h0, left = 720, 190, 10
    step = (w - 2 * left) / len(mm)
    out = [f'<svg viewBox="0 0 {w} 250" role="img" aria-label="Monthly revenue">']
    for i, r in enumerate(mm):
        bh = 150 * r["revenue"] / top
        x = left + i * step
        cx = x + step / 2
        out.append(f'<rect x="{x + 4:.1f}" y="{h0 - bh:.1f}" width="{step - 8:.1f}" '
                   f'height="{bh:.1f}" class="bar" />')
        out.append(_t("text", f"monthly.{i}.revenue", "money0", r["revenue"],
                      f' x="{cx:.1f}" y="{h0 - bh - 6:.1f}" text-anchor="middle" class="lbl"'))
        out.append(_t("text", f"monthly.{i}.month", "str", r["month"],
                      f' x="{cx:.1f}" y="{h0 + 16}" text-anchor="middle" class="lbl"'))
    out.append("</svg>")
    return "\n".join(out)


def _line(m):
    mm = m["monthly"]
    top = mm[-1]["running_total"]
    w, left = 720, 10
    step = (w - 2 * left) / (len(mm) - 1)
    pts = " ".join(f"{left + i * step:.1f},{190 - 150 * r['running_total'] / top:.1f}"
                   for i, r in enumerate(mm))
    last = len(mm) - 1
    return (f'<svg viewBox="0 0 {w} 230" role="img" aria-label="Running revenue total">\n'
            f'<polyline points="{pts}" class="ln" />\n'
            + _t("text", f"monthly.{last}.running_total", "money0", top,
                 f' x="{w - left}" y="30" text-anchor="end" class="lbl"')
            + "\n</svg>")


def _cohorts(m):
    co = m["cohorts"]
    first, idx_pos = {}, {}
    for i, c in enumerate(co):
        first.setdefault(c["cohort_month"], i)
        idx_pos.setdefault(c["month_index"], i)
    head = "".join("<th>" + _t("span", f"cohorts.{idx_pos[k]}.month_index", "int",
                               co[idx_pos[k]]["month_index"]) + "</th>"
                   for k in sorted(idx_pos))
    rows = []
    for cm, fi in first.items():
        cells = "".join(
            "<td>" + _t("span", f"cohorts.{i}.retention_pct", "pct", c["retention_pct"],
                        f' style="opacity:{0.25 + 0.75 * c["retention_pct"] / 100:.2f}"')
            + "</td>" for i, c in enumerate(co) if c["cohort_month"] == cm)
        rows.append("<tr><th>" + _t("span", f"cohorts.{fi}.cohort_month", "str", cm)
                    + " (" + _t("span", f"cohorts.{fi}.cohort_size", "int",
                                co[fi]["cohort_size"]) + ")</th>" + cells + "</tr>")
    return ("<table><thead><tr><th>Cohort (size)</th>" + head + "</tr></thead><tbody>\n"
            + "\n".join(rows) + "\n</tbody></table>")


def _top(m):
    rows = []
    for i, t in enumerate(m["top_products"]):
        rows.append("<tr>" + "".join([
            "<td>" + _t("span", f"top_products.{i}.country", "str", t["country"]) + "</td>",
            "<td>" + _t("span", f"top_products.{i}.rank", "int", t["rank"]) + "</td>",
            "<td>" + _t("span", f"top_products.{i}.stock_code", "str", t["stock_code"]) + "</td>",
            "<td>" + _t("span", f"top_products.{i}.description", "str", t["description"]) + "</td>",
            "<td>" + _t("span", f"top_products.{i}.revenue", "money", t["revenue"]) + "</td>",
        ]) + "</tr>")
    return ("<table><thead><tr><th>Country</th><th>Rank</th><th>Stock code</th>"
            "<th>Product</th><th>Revenue</th></tr></thead><tbody>\n"
            + "\n".join(rows) + "\n</tbody></table>")


